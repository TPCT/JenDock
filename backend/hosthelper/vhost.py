"""The fixed Apache virtual host template.

The helper renders the file itself from validated values (hostname, upstream port, mode and
listen addresses); callers never supply configuration text. Requirements: mod_proxy,
mod_proxy_http, mod_proxy_wstunnel, mod_rewrite, mod_headers, mod_alias and (for TLS) mod_ssl.
"""

from __future__ import annotations

import ipaddress
from dataclasses import dataclass
from pathlib import Path

from backend.hosthelper.names import WILDCARD_PREFIX, file_stem

MARKER_PREFIX = "# jendock-managed:"
FORMAT_VERSION = 1
ACME_PATH = "/.well-known/acme-challenge/"
HSTS = "max-age=31536000"
PROXY_TIMEOUT_SECONDS = 120


@dataclass(frozen=True, slots=True)
class VhostSpec:
    """The only per-domain inputs of the template."""

    hostname: str
    upstream_port: int
    tls: bool
    websocket: bool = True
    addresses: tuple[str, ...] = ()


@dataclass(frozen=True, slots=True)
class VhostPaths:
    """Fixed locations from the helper configuration."""

    cert_dir: Path
    webroot_dir: Path

    def fullchain(self, hostname: str) -> Path:
        """Certificate chain file of ``hostname``."""
        return self.cert_dir / file_stem(hostname) / "fullchain.pem"

    def private_key(self, hostname: str) -> Path:
        """Private key file of ``hostname``."""
        return self.cert_dir / file_stem(hostname) / "privkey.pem"

    def challenge_dir(self) -> Path:
        """Directory served under ``/.well-known/acme-challenge/``."""
        return self.webroot_dir / ".well-known" / "acme-challenge"


def render_vhost(spec: VhostSpec, paths: VhostPaths) -> str:
    """Return the complete vhost file for ``spec``."""
    lines = [f"{MARKER_PREFIX} host={spec.hostname} format={FORMAT_VERSION}"]
    lines.append("# Generated by the Jendock host helper. Manual edits are overwritten.")
    lines.append("")
    lines.extend(_port_80(spec, paths))
    if spec.tls:
        lines.append("")
        lines.extend(_port_443(spec, paths))
    return "\n".join(lines) + "\n"


def _server_names(hostname: str) -> list[str]:
    if hostname.startswith(WILDCARD_PREFIX):
        base = hostname[len(WILDCARD_PREFIX) :]
        return [f"    ServerName wildcard.{base}", f"    ServerAlias {hostname}"]
    return [f"    ServerName {hostname}"]


def _acme_block(paths: VhostPaths) -> list[str]:
    directory = f"{paths.challenge_dir()}/"
    return [
        f'    Alias {ACME_PATH} "{directory}"',
        f'    <Directory "{directory}">',
        "        Options None",
        "        AllowOverride None",
        "        Require all granted",
        "    </Directory>",
    ]


def _listen(spec: VhostSpec, port: int) -> str:
    """Format validated addresses for one Apache listener directive."""
    values = []
    for address in spec.addresses:
        parsed = ipaddress.ip_address(address)
        values.append(f"[{parsed}]:{port}" if parsed.version == 6 else f"{parsed}:{port}")
    return " ".join(values) if values else f"*:{port}"


def _port_80(spec: VhostSpec, paths: VhostPaths) -> list[str]:
    lines = [
        f"<VirtualHost {_listen(spec, 80)}>",
        *_server_names(spec.hostname),
        "",
        *_acme_block(paths),
        "",
    ]
    if spec.tls:
        lines.extend(_redirect_block(spec.hostname))
    else:
        lines.append(f"    ProxyPass {ACME_PATH} !")
        lines.extend(_proxy_block(spec, scheme="http"))
    lines.append("</VirtualHost>")
    return lines


def _redirect_block(hostname: str) -> list[str]:
    acme = "    RewriteCond %{REQUEST_URI} !^" + ACME_PATH.replace(".", r"\.")
    if hostname.startswith(WILDCARD_PREFIX):
        # Only names under the zone are redirected, and the captured label is re-checked, so a
        # forged Host header can never send the browser to a foreign site.
        base = hostname[len(WILDCARD_PREFIX) :]
        pattern = base.replace(".", r"\.")
        return [
            "    RewriteEngine On",
            acme,
            "    RewriteCond %{HTTP_HOST} "
            rf"^([a-z0-9-]+(?:\.[a-z0-9-]+)*)\.{pattern}(?::80)?$ [NC]",
            f"    RewriteRule ^/?(.*)$ https://%1.{base}/$1 [R=301,L]",
        ]
    return [
        "    RewriteEngine On",
        acme,
        f"    RewriteRule ^/?(.*)$ https://{hostname}/$1 [R=301,L]",
    ]


def _port_443(spec: VhostSpec, paths: VhostPaths) -> list[str]:
    lines = [f"<VirtualHost {_listen(spec, 443)}>", *_server_names(spec.hostname), ""]
    lines += [
        "    SSLEngine on",
        f'    SSLCertificateFile "{paths.fullchain(spec.hostname)}"',
        f'    SSLCertificateKeyFile "{paths.private_key(spec.hostname)}"',
        "",
        f'    Header always setifempty Strict-Transport-Security "{HSTS}"',
        '    Header always setifempty X-Content-Type-Options "nosniff"',
        '    Header always setifempty X-Frame-Options "SAMEORIGIN"',
        '    Header always setifempty Referrer-Policy "strict-origin-when-cross-origin"',
        "",
    ]
    lines.extend(_proxy_block(spec, scheme="https"))
    lines.append("</VirtualHost>")
    return lines


def _proxy_block(spec: VhostSpec, *, scheme: str) -> list[str]:
    upstream = f"127.0.0.1:{spec.upstream_port}"
    lines = [
        "    ProxyRequests Off",
        "    ProxyPreserveHost On",
        f"    ProxyTimeout {PROXY_TIMEOUT_SECONDS}",
        "    RequestHeader unset Proxy early",
        f'    RequestHeader set X-Forwarded-Proto "{scheme}"',
    ]
    if spec.websocket:
        lines += [
            "    RewriteEngine On",
            "    RewriteCond %{HTTP:Upgrade} =websocket [NC]",
            f"    RewriteRule ^/?(.*)$ ws://{upstream}/$1 [P,L]",
        ]
    lines += [
        f"    ProxyPass / http://{upstream}/ retry=0",
        f"    ProxyPassReverse / http://{upstream}/",
    ]
    return lines
